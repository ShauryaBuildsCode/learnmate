import { claudeTutorStream, type ClaudeTutorInput } from "./anthropic";
import { groqStream } from "./groq";
import type { Provider, TutorEvent } from "./types";

/**
 * Every AI task and the provider that owns it. Gemini writes content, Claude tutors,
 * Groq handles latency-critical micro-tasks (and is the labelled fallback tutor).
 */
export const TASK_ROUTES = {
  ingest_structure: "gemini",
  extract_exercises: "gemini",
  lesson_script: "claude",
  quiz_generate: "claude",
  practice_generate: "claude",
  plan_items: "gemini",
  plan_change_summary: "gemini",
  eval_judge: "gemini",
  tutor_chat: "claude",
  tutor_hint: "claude",
  tutor_diagnose: "claude",
  quick_tip: "groq",
  error_explain: "groq",
  quiz_feedback: "groq",
} as const satisfies Record<string, Provider>;

export type TaskName = keyof typeof TASK_ROUTES;

export interface TutorStreamDeps {
  claude: (input: ClaudeTutorInput) => AsyncGenerator<string>;
  groq: (
    system: string,
    turns: ClaudeTutorInput["turns"],
    maxTokens: number,
  ) => AsyncGenerator<string>;
}

const DEFAULT_DEPS: TutorStreamDeps = { claude: claudeTutorStream, groq: groqStream };

export const FALLBACK_NOTE = "Claude was unavailable, so Groq answered instead";

/**
 * Streams a tutor reply from Claude. If Claude fails (outage, rate limit, refusal chain),
 * the reply is regenerated by Groq and the stream says so explicitly: never a silent swap.
 */
export async function* streamTutor(
  input: ClaudeTutorInput,
  deps: TutorStreamDeps = DEFAULT_DEPS,
): AsyncGenerator<TutorEvent> {
  yield { type: "meta", provider: "claude" };
  let emitted = false;
  try {
    for await (const text of deps.claude(input)) {
      emitted = true;
      yield { type: "delta", text };
    }
    return;
  } catch {
    // fall through to the labelled Groq fallback
  }
  yield { type: "meta", provider: "groq", fallbackNote: FALLBACK_NOTE, reset: emitted };
  const system = `${input.persona}\n\n${input.courseBlock}`;
  for await (const text of deps.groq(system, input.turns, input.maxTokens)) {
    yield { type: "delta", text };
  }
}
